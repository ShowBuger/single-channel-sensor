"""Reproducible synthetic comparison; this is NOT a hardware accuracy report.

Run against the H7 Unicorn build, with FIRMWARE_BUILD_DIR set as in tests/README.
Writes docs/ALGORITHM_COMPARISON.md; never updates the legacy golden artifact.
"""
import math
import random
import statistics
from pathlib import Path
from test_algo_pipeline import Pipeline,V2_ONLY


def measure(profile):
    if V2_ONLY and profile==0:
        raise RuntimeError('MA03 no longer contains legacy; use historical commit 2597b35 for profile comparisons')
    p=Pipeline(profile=profile,flags=0x0D)
    rng=random.Random(20261119)
    noise=[]
    for i in range(600):
        a=[rng.gauss(0,1) for _ in range(3)]
        r=[rng.gauss(0,1) for _ in range(3)]
        _,out,_=p.step(a,r)
        if i>=100: noise.append(out[0])
    p=Pipeline(profile=profile,flags=0x05)
    for _ in range(100): p.step()
    response=[p.step((10,0,0))[1][0] for _ in range(200)]
    t10=next(i+1 for i,x in enumerate(response) if x>=1)*10
    t90=next(i+1 for i,x in enumerate(response) if x>=9)*10
    p=Pipeline(profile=profile,flags=0x09)
    p.param('kx',2)  # legacy deliberately ignores v2-only gain
    residual=[]
    for i in range(1,401):
        t=i*.01
        a=(20*math.sin(2*math.pi*t),0,0)
        r=(10*math.sin(2*math.pi*(t-.002)),0,0)
        _,out,_=p.step(a,r,actual_us=i*10000,reference_us=i*10000-2000)
        if i>100: residual.append(out[0])
    return statistics.pstdev(noise),t10,t90,math.sqrt(statistics.mean(x*x for x in residual))


if __name__=='__main__':
    old,new=measure(0),measure(1)
    rows=[('Static independent noise, output X std (uT)',old[0],new[0]),
          ('10 uT step, t10 (ms)',old[1],new[1]),
          ('10 uT step, t90 (ms)',old[2],new[2]),
          ('10 uT step, t10-t90 rise (ms)',old[2]-old[1],new[2]-new[1]),
          ('1 Hz common-mode, gain mismatch 2:1, residual RMS (uT)',old[3],new[3])]
    text='''# Algorithm synthetic comparison (2026-11-19)

Generated by `tests/compare_algo_profiles.py` using the real compiled ARM
pipeline in Unicorn, at 100 Hz. These numbers compare software behaviour;
they do not establish physical accuracy, bus timing, temperature drift or MCU
execution time. Legacy golden samples remain unchanged.

Noise and step tests enable calibration, smoothing and (for noise) compensation;
dead band, unipolar conversion, spike rejection and static decay are disabled
to avoid hiding noise or response behind nonlinear processing. Both channels
have zero offsets and mapping 1. The noise seed is fixed at 20261119.

| Metric | legacy | v2 |
|---|---:|---:|
'''
    text+='\n'.join(f'| {name} | {a:.6g} | {b:.6g} |' for name,a,b in rows)
    text+='''

Legacy smoothing uses a 500 ms moving window; v2 uses a 220 ms IIR. A different
rise time is expected. In the gain test actual amplitude is 20 uT and reference
amplitude is 10 uT, delayed by 2 ms. V2 explicitly uses Kx=2 and timestamp
alignment. Legacy keeps its historical fixed gain and prediction formula.
This test demonstrates the new gain/alignment mechanism, not a measured gain
calibration. Orientation matrices remain identity.

Before changing the field default to v2, collect the same raw paired hardware
stream with timestamps, replay both profiles and measure noise, step response,
spike false positives, pairing skew and temperature drift. Calibrate dead-band
parameters again; v2 uses combined and smoothed noise rather than sigma_actual.
'''
    target=Path(__file__).resolve().parents[1]/'docs/ALGORITHM_COMPARISON.md'
    target.write_text(text,encoding='utf-8')
    print(target)
    for name,a,b in rows: print(f'{name}: legacy={a:.6g}, v2={b:.6g}')
