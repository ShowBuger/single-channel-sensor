# ARM GNU Toolchain auto-install script
# Usage: .\tools\install_toolchain.ps1
# Run once after first clone

param(
    [string]$InstallDir = "D:\toolchain",
    [switch]$Force,
    [switch]$Help
)

$ErrorActionPreference = "Stop"

$TOOLCHAIN_VERSION = "15.3.rel1"
$TOOLCHAIN_NAME    = "arm-gnu-toolchain-$TOOLCHAIN_VERSION-mingw-w64-x86_64-arm-none-eabi"
$TOOLCHAIN_ARCHIVE = "$TOOLCHAIN_NAME.zip"
$TOOLCHAIN_URL     = "https://developer.arm.com/-/media/Files/downloads/gnu/$TOOLCHAIN_VERSION/binrel/$TOOLCHAIN_ARCHIVE"
$TOOLCHAIN_BIN     = Join-Path (Join-Path $InstallDir $TOOLCHAIN_NAME) "bin"
$TOOLCHAIN_GCC     = Join-Path $TOOLCHAIN_BIN "arm-none-eabi-gcc.exe"

function Write-Sep  { Write-Host ("=" * 52) -ForegroundColor Blue }
function Write-Info { param($m) Write-Host "  $m"   -ForegroundColor Cyan   }
function Write-Ok   { param($m) Write-Host "  + $m" -ForegroundColor Green  }
function Write-Warn { param($m) Write-Host "  ! $m" -ForegroundColor Yellow }
function Write-Err  { param($m) Write-Host "  x $m" -ForegroundColor Red    }

if ($Help) {
    Write-Host "Usage: .\tools\install_toolchain.ps1 [options]"
    Write-Host ""
    Write-Host "  -InstallDir <path>   Install directory (default: D:\toolchain)"
    Write-Host "  -Force               Re-download even if installed"
    Write-Host "  -Help                Show this help"
    exit 0
}

Write-Sep
Write-Info "ARM GNU Toolchain Installer"
Write-Sep
Write-Host "  Version    : $TOOLCHAIN_VERSION"
Write-Host "  Install to : $InstallDir"
Write-Host "  Toolchain  : $TOOLCHAIN_NAME"
Write-Sep
Write-Host ""

$alreadyInstalled = (Test-Path $TOOLCHAIN_GCC) -and (-not $Force)

if ($alreadyInstalled) {
    Write-Ok "Toolchain already installed, skipping download"
    $ver = (& $TOOLCHAIN_GCC --version | Select-Object -First 1)
    Write-Info "Version: $ver"
    Write-Host ""
} else {
    if (-not (Test-Path $InstallDir)) {
        New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
        Write-Ok "Created install directory: $InstallDir"
    }

    $archivePath  = Join-Path $InstallDir $TOOLCHAIN_ARCHIVE
    $toolchainDir = Join-Path $InstallDir $TOOLCHAIN_NAME

    if ((Test-Path $archivePath) -and (-not $Force)) {
        Write-Warn "Archive already exists, skipping download: $archivePath"
    } else {
        Write-Info "Downloading toolchain (~1 GB, please wait)..."
        Write-Info "URL: $TOOLCHAIN_URL"
        Write-Host ""
        try {
            $ProgressPreference = "Continue"
            Invoke-WebRequest -Uri $TOOLCHAIN_URL -OutFile $archivePath -UseBasicParsing
        } catch {
            Write-Err "Download failed: $_"
            Write-Warn "Manually download to: $archivePath"
            exit 1
        }
        if (-not (Test-Path $archivePath)) {
            Write-Err "Download failed, file not found"
            exit 1
        }
        $sizeMB = [math]::Round((Get-Item $archivePath).Length / 1MB, 1)
        Write-Ok "Downloaded: $archivePath ($sizeMB MB)"
    }

    if ((Test-Path $toolchainDir) -and $Force) {
        Write-Warn "Removing old toolchain directory..."
        Remove-Item -Recurse -Force $toolchainDir
    }

    if (-not (Test-Path $toolchainDir)) {
        Write-Info "Extracting toolchain (~1-3 minutes)..."
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        [System.IO.Compression.ZipFile]::ExtractToDirectory($archivePath, $InstallDir)
        if (-not (Test-Path $TOOLCHAIN_GCC)) {
            Write-Err "arm-none-eabi-gcc.exe not found after extraction"
            exit 1
        }
        Write-Ok "Extracted to: $toolchainDir"
    } else {
        Write-Ok "Toolchain directory exists, skipping extraction"
    }

    if (Test-Path $archivePath) {
        Remove-Item $archivePath -ErrorAction SilentlyContinue
        Write-Ok "Removed archive to save space"
    }
}

# Update env_setup.ps1 with resolved toolchain path
Write-Host ""
Write-Info "Updating env_setup.ps1..."
$ScriptDir   = Split-Path -Parent $PSCommandPath
$envSetupPs1 = Join-Path $ScriptDir "env_setup.ps1"

$envLines = @(
    "# PowerShell env setup -- auto-generated by install_toolchain.ps1"
    "# Usage: . .\tools\env_setup.ps1"
    ""
    '$ARM_TOOLCHAIN_PATH = "' + $TOOLCHAIN_BIN + '"'
    ""
    'if (-not (Test-Path $ARM_TOOLCHAIN_PATH)) {'
    '    Write-Host "Error: toolchain not found: $ARM_TOOLCHAIN_PATH" -ForegroundColor Red'
    '    Write-Host "Run: .\tools\install_toolchain.ps1" -ForegroundColor Yellow'
    '    return'
    '}'
    ""
    '$env:Path = "$ARM_TOOLCHAIN_PATH;$env:Path"'
    'Write-Host "+ ARM GNU Toolchain added to PATH" -ForegroundColor Green'
    'Write-Host "  $ARM_TOOLCHAIN_PATH"'
    ""
    'if (Get-Command arm-none-eabi-gcc -ErrorAction SilentlyContinue) {'
    '    $v = (arm-none-eabi-gcc --version | Select-Object -First 1)'
    '    Write-Host "+ OK: $v" -ForegroundColor Green'
    '} else {'
    '    Write-Host "x Verification failed" -ForegroundColor Red'
    '    return'
    '}'
    ""
    'Write-Host "You can now run:" -ForegroundColor Cyan'
    'Write-Host "  .\tools\build.ps1    # Build firmware"'
    'Write-Host "  .\tools\flash.ps1    # Flash firmware"'
)

$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllLines($envSetupPs1, $envLines, $utf8NoBom)
Write-Ok "Updated: $envSetupPs1"

# Optionally add to user PATH permanently
Write-Host ""
$addToPath = Read-Host "  Add toolchain to user PATH permanently? (y/N)"
if ($addToPath -match "^[yY]") {
    $userPath = [System.Environment]::GetEnvironmentVariable("Path", "User")
    if ($userPath -notlike "*$TOOLCHAIN_BIN*") {
        [System.Environment]::SetEnvironmentVariable("Path", "$userPath;$TOOLCHAIN_BIN", "User")
        Write-Ok "Added to user PATH (reopen terminal to take effect)"
    } else {
        Write-Warn "Already in PATH, skipping"
    }
} else {
    Write-Info "Skipped. Each session run: . .\tools\env_setup.ps1"
}

Write-Host ""
Write-Sep
Write-Ok "Toolchain installation complete!"
Write-Host ""
Write-Host "  Next steps:" -ForegroundColor Cyan
Write-Host "    1. Load env : . .\tools\env_setup.ps1"
Write-Host "    2. Build    : .\tools\build.ps1"
Write-Host "    3. Flash    : .\tools\flash.ps1"
Write-Sep
